-- 1. Create assessment_submissions table if it does not exist
CREATE TABLE IF NOT EXISTS public.assessment_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    name text NOT NULL,
    hospital text NOT NULL,
    mobile text NOT NULL,
    email text NOT NULL,
    city text NOT NULL,
    message text,
    total_score integer DEFAULT 0,
    score integer DEFAULT 0,
    answers jsonb DEFAULT '{}'::jsonb,
    knockouts jsonb DEFAULT '{}'::jsonb,
    user_ip text,
    user_agent text
);

-- 2. Enable Row Level Security (RLS) on the table (Optional - disable for easiest frictionless setup)
-- Option A (RECOMMENDED for frictionless public submissions): Disable RLS completely so anyone can submit
ALTER TABLE public.assessment_submissions DISABLE ROW LEVEL SECURITY;

