-- 1. Create submissions table if it does not exist
CREATE TABLE IF NOT EXISTS public.submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    name text NOT NULL,
    hospital text NOT NULL,
    mobile text NOT NULL,
    email text NOT NULL,
    city text NOT NULL,
    message text,
    user_ip text,
    user_agent text
);

-- 2. Enable Row Level Security (RLS) on the table
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;

-- 3. Safely drop policies if they already exist to avoid "already exists" errors
DROP POLICY IF EXISTS "Allow anonymous insertions" ON public.submissions;
DROP POLICY IF EXISTS "Allow public submissions" ON public.submissions;

-- 4. Create the policy to allow public/anonymous inserts to the submissions table
CREATE POLICY "Allow anonymous insertions" ON public.submissions
    FOR INSERT
    TO public
    WITH CHECK (true);

-- 5. Optional: Allow authenticated admins or service roles to read submissions
DROP POLICY IF EXISTS "Allow authenticated select" ON public.submissions;
CREATE POLICY "Allow authenticated select" ON public.submissions
    FOR SELECT
    TO authenticated
    USING (true);
